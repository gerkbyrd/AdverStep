def purify(diffpure_model, image):
    """
    Diffusion-based adversarial purification
    TAKES:
        diffpure_model: diffusion model (diffpure implementation)
        image: input batch (batch_size, C, W, H)
    GIVES
        purified: purified batch of imnages (batch_size, C, W, H)
    """
    abla=F.interpolate(image, size=(256, 256), mode='bilinear', align_corners=False)
    abla_re = diffpure_model.image_editing_sample((abla - 0.5) * 2, bs_id=0, tag=None)
    abla_re = F.interpolate(abla_re, size=(224, 224), mode='bilinear', align_corners=False)
    purified = (abla_re + 1) * 0.5
    return purified
